"use client";

import { useMemo } from "react";
import Link from "next/link";
import { Table } from "../../components/table";
import { Badge } from "../../components/badge";
import { ArrowLeftIcon } from "@/app/components/icons";
import { PreviewModal } from "@/app/components/code-preview";
import { getExactnessScoreFromValidation, ValidationResult } from "@/lib/eval";
import { TinybirdResult } from "@/lib/fetch-benchmark-data";

type QuestionMetric = {
  name: string;
  model: string;
  question: string;
  sql: string;
  executionTime: number;
  timeToFirstToken: number;
  totalDuration: number;
  bytesRead: number;
  rowsRead: number;
  queryLength: number;
  attempts: Array<{ question: { question: string } }>;
  success: boolean;
  firstAttempt: boolean;
  exactnessScore: number;
  tokens: number;
};

function toQuestionMetric(r: TinybirdResult, validationResults: ValidationResult[]): QuestionMetric {
  const exactnessScore = getExactnessScoreFromValidation(validationResults, r.provider, r.model, r.name);

  return {
    name: r.name,
    model: r.model,
    question: r.question,
    sql: r.sql || "",
    executionTime: r.sql_result_execution_time,
    timeToFirstToken: r.llm_time_to_first_token,
    totalDuration: r.llm_total_duration,
    bytesRead: r.sql_result_bytes_read || 0,
    rowsRead: r.sql_result_rows_read || 0,
    queryLength: r.sql?.length || 0,
    attempts: Array.from({ length: r.num_attempts }, () => ({
      question: { question: "" },
    })),
    success: r.sql_result_success === 1,
    firstAttempt: r.first_attempt_success === 1,
    exactnessScore: exactnessScore || 0,
    tokens: r.llm_total_tokens,
  };
}

const QuestionCell = ({ metric }: { metric: QuestionMetric }) => {
  return (
    <div className={`max-w-[475px] -m-4 p-4`}>
      <div className="truncate" title={metric.question}>
        {metric.question}
      </div>
      <PreviewModal metric={metric as any} />
    </div>
  );
};

export function ModelDetailClient({
  modelName,
  results,
  validationResults,
}: {
  modelName: string;
  results: TinybirdResult[];
  validationResults: ValidationResult[];
}) {
  const questionMetrics = useMemo(
    () => results.map((r) => toQuestionMetric(r, validationResults)),
    [results, validationResults]
  );

  const columns = [
    {
      name: "Question",
      accessorKey: "question",
      sortable: true,
      description: "The question that was asked to the model",
      cell: (row: QuestionMetric) => <QuestionCell metric={row} />,
    },
    {
      name: "Valid Query",
      accessorKey: "success",
      sortable: true,
      description: "Whether the query generated by the model is valid",
      cell: (row: QuestionMetric) => (
        <Badge status={row.success ? "success" : "error"}>
          {row.success ? "Success" : "Failed"}
        </Badge>
      ),
      type: "right" as const,
    },
    {
      name: "First Attempt",
      accessorKey: "firstAttempt",
      sortable: true,
      description: "Whether the query execution succeeded on the first try",
      cell: (row: QuestionMetric) => (
        <Badge status={row.firstAttempt ? "success" : "warning"}>
          {row.firstAttempt ? "Yes" : "No"}
        </Badge>
      ),
      type: "right" as const,
    },
    {
      name: "Exactness",
      accessorKey: "exactnessScore",
      sortable: true,
      description: "How similar the model's output is to the human's output",
      cell: (row: QuestionMetric) => (
        <div className="inline-flex items-center">
          <div
            className={`w-2 h-2 rounded-full mr-2 ${
              row.exactnessScore > 75
                ? "bg-[#27F795]"
                : row.exactnessScore >= 50
                ? "bg-[#F7D727]"
                : "bg-[#F72727]"
            }`}
          />
          <span className="font-mono">{row.exactnessScore.toFixed(2)}</span>
        </div>
      ),
      type: "right" as const,
    },
    {
      name: "Query Latency",
      accessorKey: "executionTime",
      sortable: true,
      description: "Time taken to execute the query in milliseconds",
      cell: (row: QuestionMetric) => (
        <span className="font-mono">
          {(row.executionTime * 1000).toLocaleString("en-US")} ms
        </span>
      ),
      type: "right" as const,
    },
    {
      name: "LLM Gen",
      accessorKey: "totalDuration",
      sortable: true,
      description: "Time for the LLM to generate the SQL query in seconds",
      cell: (row: QuestionMetric) => (
        <span className="font-mono">{row.totalDuration.toLocaleString("en-US")} s</span>
      ),
      type: "right" as const,
    },
    {
      name: "Attempts",
      accessorKey: "attempts",
      sortable: true,
      description: "Number of attempts needed for this query",
      cell: (row: QuestionMetric) => (
        <span className="font-mono">{row.attempts.length}</span>
      ),
      type: "right" as const,
    },
    {
      name: "Rows Read",
      accessorKey: "rowsRead",
      sortable: true,
      description: "Number of rows read by this query (lower is better)",
      cell: (row: QuestionMetric) => (
        <span className="font-mono">{row.rowsRead.toLocaleString("en-US")}</span>
      ),
      type: "right" as const,
    },
    {
      name: "Data Read",
      accessorKey: "bytesRead",
      sortable: true,
      description: "Amount of data read by this query in MB",
      cell: (row: QuestionMetric) => (
        <span className="font-mono">
          {(row.bytesRead / (1024 * 1024)).toLocaleString("en-US", {
            minimumFractionDigits: 2,
            maximumFractionDigits: 2,
          })}{" "}
          MB
        </span>
      ),
      type: "right" as const,
    },
    {
      name: "Query Length",
      accessorKey: "queryLength",
      sortable: true,
      description: "Length of the generated SQL query in characters",
      cell: (row: QuestionMetric) => (
        <span className="font-mono">{row.queryLength}</span>
      ),
      type: "right" as const,
    },
    {
      name: "Tokens",
      accessorKey: "tokens",
      sortable: true,
      description: "Number of tokens used to generate the query",
      cell: (row: QuestionMetric) => (
        <span className="font-mono">{row.tokens.toLocaleString("en-US")}</span>
      ),
      type: "right" as const,
    },
  ];

  if (questionMetrics.length === 0) {
    return (
      <div className="min-h-screen p-8 font-sans">
        <div className="mb-8">
          <Link
            href="/"
            className="text-white hover:text-[#27F795] flex items-center gap-2"
          >
            <ArrowLeftIcon /> Back
          </Link>
        </div>
        <div className="text-center text-xl">
          No results found for model: {modelName}
        </div>
      </div>
    );
  }

  return (
    <div className="min-h-screen py-8 px-4 lg:px-8 font-sans">
      <div className="mb-8">
        <Link
          href="/"
          className="text-white hover:text-[#27F795] flex items-center gap-2"
        >
          <ArrowLeftIcon /> Back
        </Link>
      </div>

      <h1 className="text-3xl mb-8">Detailed Results for {modelName}</h1>

      <div className="overflow-x-auto">
        <Table<QuestionMetric>
          columns={columns}
          data={questionMetrics}
          defaultSort={{ key: "question", direction: "asc" }}
        />
      </div>
    </div>
  );
}
